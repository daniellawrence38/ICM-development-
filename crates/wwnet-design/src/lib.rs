//! DS 50 gravity sewer design engine.
//!
//! Computes local loading per sub-catchment (4.2.1), accumulates flow down the gravity
//! network (stopping at pump station wet wells), runs the clause-referenced conduit checks of
//! `wwnet-rules` and adds node checks (falls through ACs, drop ACs).
pub mod service;

use serde::Serialize;
use std::collections::HashMap;
use wwnet_core::gpkg::ConduitResult;
use wwnet_core::{
    Conduit, Error, Issue, LandUse, Material, Model, Network, Node, NodeType, PumpStation, Result,
    Severity, Subcatchment,
};
use wwnet_hydraulics as hyd;
use wwnet_rules as wr;
use wwnet_rules::{Check, CheckResult, ConduitDesignInput, LandUseClass, RuleSet};

/// Design result for one conduit.
#[derive(Debug, Clone, Serialize)]
pub struct ConduitDesign {
    pub conduit_id: String,
    pub dn: i64,
    pub grade_1in: Option<f64>,
    /// Accumulated gravity GSDF (L/s).
    pub gsdf_lps: f64,
    /// Accumulated average dry weather flow from node loads (L/s); already included in
    /// `gsdf_lps` at the peaking factor.
    pub adwf_lps: f64,
    /// Pumped inflow from upstream pump stations (L/s).
    pub pumped_lps: f64,
    pub total_lps: f64,
    /// Governing capacity (L/s): the lesser of the Table 4.4 maximum allowable flow for the
    /// grade band and the hydraulic capacity at the d/D limit.
    pub capacity_lps: Option<f64>,
    /// Colebrook-White part-full capacity at the d/D limit (L/s).
    pub hydraulic_capacity_lps: Option<f64>,
    /// DS50 Table 4.4 maximum allowable flow for the grade band (L/s); `None` when the
    /// grade is unknown or outside the bands.
    pub table44_lps: Option<f64>,
    /// d/D at the total flow (`None` if the pipe cannot carry it part-full or grade unknown).
    pub d_over_d: Option<f64>,
    pub velocity_mps: Option<f64>,
    pub land_use_class: LandUseClass,
    pub result: CheckResult,
    pub checks: Vec<Check>,
}

impl ConduitDesign {
    /// Message of the first check carrying the worst result, if any check exists.
    pub fn worst_message(&self) -> Option<&str> {
        self.checks
            .iter()
            .find(|c| c.result == self.result)
            .map(|c| c.message.as_str())
    }
}

/// Flow summary at a node.
#[derive(Debug, Clone, Serialize)]
pub struct NodeFlow {
    pub node_id: String,
    /// GSDF generated by sub-catchments draining to this node (L/s).
    pub local_gsdf_lps: f64,
    /// ADWF from node loads at this node (L/s); its GSDF share is in `local_gsdf_lps`.
    pub local_adwf_lps: f64,
    pub local_daily_flow_l_day: f64,
    /// DS 50 3.5(c) design data strings, one per sub-catchment.
    pub design_data: Vec<String>,
    /// Gravity GSDF arriving at (and generated at) this node (L/s).
    pub accumulated_gsdf_lps: f64,
    /// Gravity ADWF arriving at (and generated at) this node (L/s).
    pub accumulated_adwf_lps: f64,
    /// Pumped inflow stream passing this node (L/s).
    pub pumped_lps: f64,
    /// Pump station discharge injected at this node (L/s).
    pub pump_discharge_lps: f64,
}

#[derive(Debug, Clone, Default, Serialize)]
pub struct DesignSummary {
    pub conduits: usize,
    pub pass: usize,
    pub warn: usize,
    pub fail: usize,
    /// Conduit ends where the cover check could not be run (no surface/invert level).
    pub cover_not_checked_ends: usize,
    /// Sum of local GSDF over all sub-catchments (L/s).
    pub total_local_gsdf_lps: f64,
    /// Sum of local ADWF over all node loads (L/s).
    pub total_local_adwf_lps: f64,
    /// Gravity ADWF reaching terminal nodes (L/s).
    pub terminal_adwf_lps: f64,
    /// Peaking factor applied to ADWF to give GSDF.
    pub peaking_factor: f64,
    /// Gravity GSDF reaching terminal nodes (outfalls / sinks, excluding wet wells).
    pub terminal_gsdf_lps: f64,
}

#[derive(Debug, Clone, Serialize)]
pub struct DesignOutput {
    pub conduit_results: Vec<ConduitDesign>,
    pub node_flows: Vec<NodeFlow>,
    pub issues: Vec<Issue>,
    pub summary: DesignSummary,
}

fn issue(
    sev: Severity,
    code: &str,
    ot: &str,
    id: &str,
    clause: Option<&str>,
    msg: String,
) -> Issue {
    Issue {
        severity: sev,
        code: code.into(),
        object_type: ot.into(),
        object_id: id.into(),
        clause: clause.map(String::from),
        message: msg,
    }
}

fn fmt_num(x: f64) -> String {
    format!("{}", (x * 100.0).round() / 100.0)
}

fn class_rank(c: LandUseClass) -> u8 {
    match c {
        LandUseClass::Residential => 0,
        LandUseClass::SmallCommercial => 1,
        LandUseClass::IndustrialLargeCommercial => 2,
    }
}

fn max_class(a: LandUseClass, b: LandUseClass) -> LandUseClass {
    if class_rank(b) > class_rank(a) {
        b
    } else {
        a
    }
}

#[derive(Debug, Clone, Copy, Default)]
struct Flow {
    g: f64,
    a: f64,
    p: f64,
    class: LandUseClass,
}

impl Flow {
    fn add(&mut self, o: &Flow) {
        self.g += o.g;
        self.a += o.a;
        self.p += o.p;
        self.class = max_class(self.class, o.class);
    }
}

#[derive(Debug, Default)]
struct Local {
    gsdf: f64,
    adwf: f64,
    daily: f64,
    labels: Vec<String>,
    class: LandUseClass,
}

fn to_rules_region(r: wwnet_core::Region) -> wr::Region {
    match r {
        wwnet_core::Region::South => wr::Region::South,
        wwnet_core::Region::North => wr::Region::North,
    }
}

fn to_rules_ground(g: wwnet_core::Ground) -> wr::Ground {
    match g {
        wwnet_core::Ground::Dry => wr::Ground::Dry,
        wwnet_core::Ground::Wet => wr::Ground::Wet,
    }
}

fn to_rules_location(l: wwnet_core::Location) -> wr::Location {
    match l {
        wwnet_core::Location::RoadReserve => wr::Location::RoadReserve,
        wwnet_core::Location::TrafficableRow => wr::Location::TrafficableRow,
        _ => wr::Location::Elsewhere,
    }
}

/// Net area (ha) for a sub-catchment per 4.2.1(k); `None` if it cannot be determined.
fn net_area(s: &Subcatchment, rules: &RuleSet, out: &mut Vec<Issue>) -> Option<f64> {
    let id = &s.subcatchment_id;
    if let Some(a) = s.net_area_ha {
        return Some(a);
    }
    if s.broadacre {
        if let Some(g) = s.gross_area_ha {
            let ded = rules.loading.broadacre_pos_minor_road_deduction;
            let a = g * (1.0 - ded);
            out.push(issue(
                Severity::Info,
                "design_net_area_broadacre",
                "subcatchment",
                id,
                Some("DS50 4.2.1(k)"),
                format!("net area {a:.2} ha derived from gross {g:.2} ha x (1 - {ded})"),
            ));
            return Some(a);
        }
    }
    if let Some(g) = &s.geom {
        let a = g.area() / 10_000.0;
        out.push(issue(
            Severity::Info,
            "design_net_area_geometry",
            "subcatchment",
            id,
            None,
            format!("net area not set; {a:.2} ha taken from geometry"),
        ));
        return Some(a);
    }
    out.push(issue(
        Severity::Warning,
        "design_no_area",
        "subcatchment",
        id,
        None,
        "no net area, gross area or geometry; sub-catchment ignored".into(),
    ));
    None
}

fn local_loads(model: &Model, rules: &RuleSet, out: &mut Vec<Issue>) -> HashMap<String, Local> {
    let mut map: HashMap<String, Local> = HashMap::new();
    for s in &model.subcatchments {
        let id = &s.subcatchment_id;
        if let Some(a) = s.adwf_lps {
            // Manual ADWF replaces the land-use / R-code loading (extra flow still applies).
            if !a.is_finite() || a < 0.0 {
                out.push(issue(
                    Severity::Warning,
                    "design_bad_area",
                    "subcatchment",
                    id,
                    None,
                    format!("invalid manual ADWF {a}; sub-catchment ignored"),
                ));
                continue;
            }
            let peak = model.load_settings.peaking_factor;
            out.push(issue(
                Severity::Info,
                "design_manual_adwf",
                "subcatchment",
                id,
                None,
                format!(
                    "manual ADWF {a:.3} L/s used instead of land-use loading; GSDF = ADWF x {peak}"
                ),
            ));
            let l = map.entry(s.outlet_node_id.clone()).or_default();
            l.adwf += a;
            l.gsdf += a * peak + s.extra_flow_lps;
            l.daily += a * 86400.0;
            l.labels.push(format!("manual ADWF {} L/s", fmt_num(a)));
            continue;
        }
        let Some(area) = net_area(s, rules, out) else {
            continue;
        };
        if !area.is_finite() || area < 0.0 {
            out.push(issue(
                Severity::Warning,
                "design_bad_area",
                "subcatchment",
                id,
                None,
                format!("invalid net area {area}; sub-catchment ignored"),
            ));
            continue;
        }
        let (region, ground) = (to_rules_region(s.region), to_rules_ground(s.ground));
        let small_max = rules.sizing.small_commercial_max_ha;
        let (mut gsdf, daily, label, class) = if s.land_use == LandUse::Residential {
            match rules.residential_rate(region, ground, &s.rcode) {
                Ok(r) => {
                    if let Some(note) = &r.note {
                        out.push(issue(
                            Severity::Info,
                            "design_rate_note",
                            "subcatchment",
                            id,
                            Some(&r.clause),
                            note.clone(),
                        ));
                    }
                    (
                        r.gsdf_lps_per_ha * area,
                        area * r.persons_per_net_ha * r.lpd,
                        format!(
                            "{}-{}/{}-{:.2}",
                            fmt_num(area),
                            fmt_num(r.persons_per_net_ha),
                            fmt_num(r.lpd),
                            r.gsdf_lps_per_ha
                        ),
                        LandUseClass::Residential,
                    )
                }
                Err(e) => {
                    out.push(issue(
                        Severity::Warning,
                        "design_rate_missing",
                        "subcatchment",
                        id,
                        Some("DS50 Table 4.1/4.2"),
                        format!("{e}; sub-catchment ignored"),
                    ));
                    continue;
                }
            }
        } else {
            let (key, big_always) = match s.land_use {
                LandUse::Commercial => ("suburban_commercial_school_hospital_public", false),
                LandUse::HotelMotel => ("hotel_motel", false),
                LandUse::PerthCba => ("perth_cba", false),
                _ => ("industrial", true),
            };
            match rules.non_residential_rate(region, ground, key) {
                Ok(r) => {
                    let class = if big_always || area > small_max {
                        LandUseClass::IndustrialLargeCommercial
                    } else {
                        LandUseClass::SmallCommercial
                    };
                    (
                        r.gsdf_lps_per_ha * area,
                        area * r.l_per_net_ha_day,
                        format!(
                            "{}-{}-{:.2}",
                            fmt_num(area),
                            fmt_num(r.l_per_net_ha_day),
                            r.gsdf_lps_per_ha
                        ),
                        class,
                    )
                }
                Err(e) => {
                    out.push(issue(
                        Severity::Warning,
                        "design_rate_missing",
                        "subcatchment",
                        id,
                        Some("DS50 Table 4.3"),
                        format!("{e}; sub-catchment ignored"),
                    ));
                    continue;
                }
            }
        };
        gsdf += s.extra_flow_lps;
        let l = map.entry(s.outlet_node_id.clone()).or_default();
        l.gsdf += gsdf;
        l.daily += daily;
        l.labels.push(label);
        l.class = max_class(l.class, class);
    }
    map
}

/// Grade-dependent rules, filtered out when the grade is unknown.
const GRADE_RULES: &[&str] = &[
    "min_grade",
    "max_grade",
    "max_flow",
    "depth_ratio",
    "pressure_main_discharge",
];

fn worst(checks: &[Check]) -> CheckResult {
    let mut w = CheckResult::Pass;
    for c in checks {
        match (w, c.result) {
            (_, CheckResult::Fail) => return CheckResult::Fail,
            (CheckResult::Pass, CheckResult::Warn) => w = CheckResult::Warn,
            _ => {}
        }
    }
    w
}

fn data_check(msg: String) -> Check {
    Check {
        rule: "missing_data".into(),
        clause: String::new(),
        value: 0.0,
        limit: 0.0,
        result: CheckResult::Warn,
        message: msg,
    }
}

fn design_conduit(
    c: &Conduit,
    flow: &Flow,
    nodes: &HashMap<&str, &Node>,
    rules: &RuleSet,
    issues: &mut Vec<Issue>,
) -> ConduitDesign {
    let cid = &c.conduit_id;
    let (us_n, ds_n) = (
        nodes.get(c.us_node_id.as_str()),
        nodes.get(c.ds_node_id.as_str()),
    );
    let us_inv = c.us_invert.or(us_n.and_then(|n| n.invert_level));
    let ds_inv = c.ds_invert.or(ds_n.and_then(|n| n.invert_level));
    let length = c.effective_length();
    let id_mm = c.effective_id_mm();
    let total = flow.g + flow.p;

    let mut extra: Vec<Check> = Vec::new();
    let mut missing: Vec<String> = Vec::new();

    // Grade.
    let mut grade: Option<f64> = None;
    match (us_inv, ds_inv, length) {
        (Some(u), Some(d), Some(l)) if l > 0.0 => {
            if u - d > 1e-9 {
                grade = Some(l / (u - d));
            } else {
                extra.push(Check {
                    rule: "min_grade".into(),
                    clause: "DS50 Table 4.4".into(),
                    value: 0.0,
                    limit: 0.0,
                    result: CheckResult::Fail,
                    message: format!(
                        "conduit is flat or falls upstream (inverts {u:.3} -> {d:.3})"
                    ),
                });
            }
        }
        _ => {
            missing.push("grade (inverts or length missing); grade-dependent checks skipped".into())
        }
    }
    if length.is_none() {
        missing.push("length; AC spacing check skipped".into());
    }

    // Cover at each end (NaN if unknown). Missing levels only produce an info note.
    let cover = |n: Option<&&Node>, inv: Option<f64>| match (n.and_then(|n| n.surface_level), inv) {
        (Some(s), Some(i)) => s - i - id_mm / 1000.0,
        _ => f64::NAN,
    };
    let (us_cover, ds_cover) = (cover(us_n, us_inv), cover(ds_n, ds_inv));
    let mut cover_info: Vec<Check> = Vec::new();
    for (cv, n, node_id, inv) in [
        (us_cover, us_n, &c.us_node_id, us_inv),
        (ds_cover, ds_n, &c.ds_node_id, ds_inv),
    ] {
        if cv.is_nan() {
            let why = if n.and_then(|n| n.surface_level).is_none() {
                "no surface level"
            } else {
                debug_assert!(inv.is_none());
                "no invert level"
            };
            cover_info.push(Check {
                rule: "cover_not_checked".into(),
                clause: "DS50 4.9".into(),
                value: 0.0,
                limit: 0.0,
                result: CheckResult::Info,
                message: format!("cover not checked ({why} at {node_id})"),
            });
        }
    }

    let input = ConduitDesignInput {
        dn: c.dn.max(0) as u32,
        grade_1in: grade.unwrap_or(200.0),
        gsdf_lps: flow.g,
        pumped_inflow_lps: flow.p,
        land_use_class: flow.class,
        length_m: length.unwrap_or(0.0),
        us_cover_m: us_cover,
        ds_cover_m: ds_cover,
        location: to_rules_location(c.location),
        levels_uncertain: false,
    };
    let mut checks: Vec<Check> = wr::check_conduit(rules, &input)
        .into_iter()
        .filter(|k| {
            !(grade.is_none() && GRADE_RULES.contains(&k.rule.as_str())
                || length.is_none() && k.rule == "ac_spacing"
                || k.rule == "min_cover" && k.value.is_nan())
        })
        .collect();
    checks.extend(extra);
    checks.extend(cover_info);
    for m in &missing {
        issues.push(issue(
            Severity::Warning,
            "design_missing_data",
            "conduit",
            cid,
            None,
            format!("missing {m}"),
        ));
        checks.push(data_check(format!("missing {m}")));
    }

    // Hydraulics at the conduit's own ID and ks.
    let (mut capacity, mut hyd_cap, mut t44, mut dod, mut vel) = (None, None, None, None, None);
    if let Some(g) = grade {
        let d = id_mm / 1000.0;
        let slope = hyd::slope_from_1in(g);
        let ks = c.ks_mm.unwrap_or(rules.hydraulics.ks_mm) / 1000.0;
        let lim = rules.max_d_over_d(c.dn.max(0) as u32);
        let h = hyd::part_full_flow(d, slope, lim, ks) * 1000.0;
        t44 = rules
            .max_allowable_flow(c.dn.max(0) as u32, g)
            .map(|(q, _)| q);
        hyd_cap = Some(h);
        capacity = Some(t44.map_or(h, |q| q.min(h)));
        dod = hyd::depth_ratio_for_flow(total / 1000.0, d, slope, ks);
        vel = hyd::velocity_at_flow(total / 1000.0, d, slope, ks);
    }

    for k in &checks {
        let sev = match k.result {
            CheckResult::Pass => continue,
            CheckResult::Warn => Severity::Warning,
            CheckResult::Fail => Severity::Error,
            CheckResult::Info => continue,
        };
        if k.rule == "missing_data" {
            continue;
        }
        issues.push(issue(
            sev,
            &format!("design_{}", k.rule),
            "conduit",
            cid,
            Some(&k.clause),
            k.message.clone(),
        ));
    }

    ConduitDesign {
        conduit_id: cid.clone(),
        dn: c.dn,
        grade_1in: grade,
        gsdf_lps: flow.g,
        adwf_lps: flow.a,
        pumped_lps: flow.p,
        total_lps: total,
        capacity_lps: capacity,
        hydraulic_capacity_lps: hyd_cap,
        table44_lps: t44,
        d_over_d: dod,
        velocity_mps: vel,
        land_use_class: flow.class,
        result: worst(&checks),
        checks,
    }
}

fn node_checks(model: &Model, rules: &RuleSet, issues: &mut Vec<Issue>) {
    const TOL: f64 = 0.0005;
    let mut ins: HashMap<&str, Vec<&Conduit>> = HashMap::new();
    let mut outs: HashMap<&str, Vec<&Conduit>> = HashMap::new();
    for c in &model.conduits {
        ins.entry(c.ds_node_id.as_str()).or_default().push(c);
        outs.entry(c.us_node_id.as_str()).or_default().push(c);
    }
    for n in &model.nodes {
        if !matches!(n.node_type, NodeType::Ac | NodeType::DropAc) {
            continue;
        }
        let (Some(is), Some(os)) = (ins.get(n.node_id.as_str()), outs.get(n.node_id.as_str()))
        else {
            continue;
        };
        for i in is {
            for o in os {
                let (Some(hi), Some(lo)) = (i.ds_invert, o.us_invert) else {
                    continue;
                };
                let fall = hi - lo;
                let (idn, odn) = (i.dn.max(0) as u32, o.dn.max(0) as u32);
                if n.node_type == NodeType::Ac {
                    if let Some(req) = rules.ac_fall(idn, odn) {
                        if fall < req - TOL {
                            issues.push(issue(
                                Severity::Warning,
                                "design_ac_fall",
                                "node",
                                &n.node_id,
                                Some("DS50 Table 4.8"),
                                format!(
                                    "fall through AC {fall:.3} m ({} DN{idn} -> {} DN{odn}) is less than required {req:.2} m",
                                    i.conduit_id, o.conduit_id
                                ),
                            ));
                        }
                    }
                } else {
                    let mat = if i.material == Material::Vc {
                        wr::Material::Vc
                    } else {
                        wr::Material::Pvc
                    };
                    match rules.drop_min(idn, odn, mat) {
                        Some(req) if fall < req - TOL => issues.push(issue(
                            Severity::Warning,
                            "design_drop_ac",
                            "node",
                            &n.node_id,
                            Some("DS50 Table 4.5"),
                            format!(
                                "drop {fall:.3} m ({} DN{idn} -> {} DN{odn}) is less than minimum {req:.2} m",
                                i.conduit_id, o.conduit_id
                            ),
                        )),
                        Some(_) => {}
                        None => issues.push(issue(
                            Severity::Info,
                            "design_drop_ac_no_entry",
                            "node",
                            &n.node_id,
                            Some("DS50 Table 4.5"),
                            format!("no Table 4.5 entry for drop DN{idn} / sewer DN{odn}"),
                        )),
                    }
                }
            }
        }
    }
}

/// Add node loads (ADWF, and its GSDF at the peaking factor) to the local loads.
fn add_node_loads(model: &Model, locals: &mut HashMap<String, Local>, issues: &mut Vec<Issue>) {
    let ls = &model.load_settings;
    let node_ids: std::collections::HashSet<&str> =
        model.nodes.iter().map(|n| n.node_id.as_str()).collect();
    for l in &model.node_loads {
        let adwf = l.effective_adwf_lps(ls.adwf_per_connection_lpd);
        if !adwf.is_finite() || adwf < 0.0 {
            issues.push(issue(
                Severity::Warning,
                "design_bad_load",
                "node",
                &l.node_id,
                None,
                format!("node load {} has invalid ADWF {adwf}; ignored", l.load_id),
            ));
            continue;
        }
        if l.adwf_lps.is_none() && l.connections.is_none() {
            issues.push(issue(
                Severity::Warning,
                "design_bad_load",
                "node",
                &l.node_id,
                None,
                format!(
                    "node load {} has neither connections nor ADWF; ignored",
                    l.load_id
                ),
            ));
            continue;
        }
        if !node_ids.contains(l.node_id.as_str()) {
            issues.push(issue(
                Severity::Warning,
                "design_load_node_missing",
                "node",
                &l.node_id,
                None,
                format!(
                    "node load {} refers to a node that does not exist; its flow is lost",
                    l.load_id
                ),
            ));
            continue;
        }
        let e = locals.entry(l.node_id.clone()).or_default();
        e.adwf += adwf;
        e.gsdf += adwf * ls.peaking_factor;
        e.daily += adwf * 86400.0;
    }
}

/// Average dry weather flow (L/s) of one sub-catchment for dynamic simulation, reusing the design
/// loading code: the manual `adwf_lps` when set, otherwise the DS 50 daily flow / 86400 (i.e.
/// GSDF / peaking at the DS 50 rates). Special `extra_flow_lps` is not ADWF and is excluded.
/// Returns `None` (with the reason in the issues) when the loading cannot be determined.
pub fn subcatchment_adwf_lps(
    model: &Model,
    s: &Subcatchment,
    rules: &RuleSet,
) -> (Option<f64>, Vec<Issue>) {
    let single = Model {
        subcatchments: vec![s.clone()],
        load_settings: model.load_settings.clone(),
        ..Model::default()
    };
    let mut issues = Vec::new();
    let locals = local_loads(&single, rules, &mut issues);
    let adwf = locals.values().next().map(|l| l.daily / 86400.0);
    (adwf, issues)
}

/// Run the DS 50 design on a model.
pub fn run_design(model: &Model, rules: &RuleSet) -> Result<DesignOutput> {
    let mut issues: Vec<Issue> = Vec::new();
    let mut locals = local_loads(model, rules, &mut issues);
    add_node_loads(model, &mut locals, &mut issues);
    for outlet in locals.keys() {
        if !model.nodes.iter().any(|n| &n.node_id == outlet) {
            issues.push(issue(
                Severity::Warning,
                "design_outlet_missing",
                "node",
                outlet,
                None,
                "sub-catchment outlet node does not exist; its flow is lost".into(),
            ));
        }
    }

    let net = Network::build(model)?;
    let order: Vec<String> = net
        .topological_order()?
        .into_iter()
        .map(String::from)
        .collect();
    let nodes: HashMap<&str, &Node> = model
        .nodes
        .iter()
        .rev()
        .map(|n| (n.node_id.as_str(), n))
        .collect();
    let mut outs: HashMap<&str, Vec<&Conduit>> = HashMap::new();
    for c in &model.conduits {
        if nodes.contains_key(c.us_node_id.as_str()) && nodes.contains_key(c.ds_node_id.as_str()) {
            outs.entry(c.us_node_id.as_str()).or_default().push(c);
        }
    }
    let ps_by_wet: HashMap<&str, &PumpStation> = model
        .pump_stations
        .iter()
        .filter_map(|p| p.wet_well_node_id.as_deref().map(|w| (w, p)))
        .collect();

    let mut state: HashMap<String, Flow> = HashMap::new();
    let mut inject: HashMap<String, f64> = HashMap::new();
    let mut conduit_flow: HashMap<&str, Flow> = HashMap::new();
    let mut node_flows = Vec::new();
    let mut terminal = 0.0;
    let mut terminal_adwf = 0.0;

    for id in &order {
        let mut f = state.remove(id).unwrap_or_default();
        let empty = Local::default();
        let local = locals.get(id).unwrap_or(&empty);
        f.g += local.gsdf;
        f.a += local.adwf;
        f.class = max_class(f.class, local.class);
        let accumulated = f.g;
        let accumulated_adwf = f.a;
        let pumped_here = f.p;

        if let Some(ps) = ps_by_wet.get(id.as_str()) {
            let rate = match ps.pump_rate_lps {
                Some(r) => r,
                None => {
                    issues.push(issue(
                        Severity::Warning,
                        "design_pump_rate_missing",
                        "pump_station",
                        &ps.ps_id,
                        Some("DS50 4.2.1(l)"),
                        format!(
                            "pump rate not set; using accumulated flow {:.2} L/s at wet well",
                            f.g + f.p
                        ),
                    ));
                    f.g + f.p
                }
            };
            match ps
                .discharge_node_id
                .as_deref()
                .filter(|d| nodes.contains_key(d))
            {
                Some(d) => {
                    let st = state.entry(d.to_string()).or_default();
                    st.p += rate;
                    st.class = max_class(st.class, f.class);
                    *inject.entry(d.to_string()).or_default() += rate;
                }
                None => issues.push(issue(
                    Severity::Warning,
                    "design_pump_no_discharge",
                    "pump_station",
                    &ps.ps_id,
                    None,
                    "pump station has no valid discharge node; pumped flow is lost".into(),
                )),
            }
            f.g = 0.0;
            f.a = 0.0;
            f.p = 0.0;
        }

        let out_list = outs.get(id.as_str()).map(Vec::as_slice).unwrap_or(&[]);
        if out_list.len() > 1 {
            issues.push(issue(
                Severity::Warning,
                "design_bifurcation",
                "node",
                id,
                None,
                format!(
                    "node has {} outgoing conduits; all flow sent down {}",
                    out_list.len(),
                    out_list[0].conduit_id
                ),
            ));
        }
        if let Some(c) = out_list.first() {
            conduit_flow.insert(c.conduit_id.as_str(), f);
            state.entry(c.ds_node_id.clone()).or_default().add(&f);
        } else if !ps_by_wet.contains_key(id.as_str()) {
            terminal += accumulated;
            terminal_adwf += accumulated_adwf;
        }

        node_flows.push(NodeFlow {
            node_id: id.clone(),
            local_gsdf_lps: local.gsdf,
            local_adwf_lps: local.adwf,
            local_daily_flow_l_day: local.daily,
            design_data: local.labels.clone(),
            accumulated_gsdf_lps: accumulated,
            accumulated_adwf_lps: accumulated_adwf,
            pumped_lps: pumped_here + inject.get(id).copied().unwrap_or(0.0),
            pump_discharge_lps: inject.get(id).copied().unwrap_or(0.0),
        });
    }
    // Isolated nodes unknown to the graph cannot occur (all nodes are vertices).
    let mut conduit_results = Vec::new();
    for c in &model.conduits {
        let flow = conduit_flow
            .get(c.conduit_id.as_str())
            .copied()
            .unwrap_or_default();
        conduit_results.push(design_conduit(c, &flow, &nodes, rules, &mut issues));
    }
    node_checks(model, rules, &mut issues);

    let count = |r| conduit_results.iter().filter(|c| c.result == r).count();
    let summary = DesignSummary {
        conduits: conduit_results.len(),
        pass: count(CheckResult::Pass),
        warn: count(CheckResult::Warn),
        fail: count(CheckResult::Fail),
        cover_not_checked_ends: conduit_results
            .iter()
            .flat_map(|c| &c.checks)
            .filter(|k| k.rule == "cover_not_checked")
            .count(),
        total_local_gsdf_lps: node_flows.iter().map(|n| n.local_gsdf_lps).sum(),
        terminal_gsdf_lps: terminal,
        total_local_adwf_lps: node_flows.iter().map(|n| n.local_adwf_lps).sum(),
        terminal_adwf_lps: terminal_adwf,
        peaking_factor: model.load_settings.peaking_factor,
    };
    Ok(DesignOutput {
        conduit_results,
        node_flows,
        issues,
        summary,
    })
}

/// Convert design results to `wwn_results_conduits` rows.
pub fn to_conduit_results(out: &DesignOutput, rules: &RuleSet) -> Result<Vec<ConduitResult>> {
    let label = format!("{} {} ({})", rules.standard, rules.revision, rules.year);
    out.conduit_results
        .iter()
        .map(|c| {
            let messages = serde_json::to_string(&serde_json::json!({
                "checks": c.checks,
                "hydraulic_capacity_lps": c.hydraulic_capacity_lps,
                "table44_lps": c.table44_lps,
            }))
            .map_err(|e| Error::Other(format!("cannot encode messages: {e}")))?;
            Ok(ConduitResult {
                conduit_id: c.conduit_id.clone(),
                ruleset: Some(label.clone()),
                gsdf_lps: Some(c.gsdf_lps),
                capacity_lps: c.capacity_lps,
                d_over_d: c.d_over_d,
                velocity_mps: c.velocity_mps,
                grade_1in: c.grade_1in,
                result: match c.result {
                    CheckResult::Pass => "pass",
                    CheckResult::Warn => "warn",
                    CheckResult::Fail => "fail",
                    CheckResult::Info => "info",
                }
                .into(),
                messages: Some(messages),
            })
        })
        .collect()
}
